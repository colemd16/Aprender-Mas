// Writes src/content/verb-past-english.ts: each verb's English simple past ("spoke",
// "went", "woke up"), from the preterite rows of Fred Jehle's CSV. The database keeps the
// base form ("to speak") but not the past, which the verb challenge needs to say what a
// form means ("(if) you spoke"). Run after changing the verb data: npm run past-english
import fs from "node:fs";

const csv = fs.readFileSync("data/fred-jehle-spanish-verbs/jehle_verb_database.csv", "utf8");
const parseLine = (line) => [...line.matchAll(/"((?:[^"]|"")*)"|([^,]+)|(?<=,)(?=,|$)/g)].map((m) => (m[1] ?? m[2] ?? "").replace(/""/g, '"'));
const [header, ...rows] = csv.split(/\r?\n/).filter(Boolean).map(parseLine);
const col = (name) => header.indexOf(name);
const past = {};
for (const r of rows) {
  if (r[col("mood")] !== "Indicativo" || r[col("tense")] !== "Pretérito") continue;
  // "I spoke" / "I was able, could" → "spoke" / "was able"
  const english = r[col("verb_english")].replace(/^I\s+/, "").split(/[,;]/)[0].trim();
  if (english) past[r[col("infinitive")]] = english;
}
const body = Object.entries(past)
  .sort(([a], [b]) => a.localeCompare(b, "es"))
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
fs.writeFileSync(
  "src/content/verb-past-english.ts",
  `// Generated by scripts/extract-past-english.mjs from Fred Jehle's Spanish Verb Database
// (CC BY-NC-SA 3.0). Each verb's English simple past, for saying what a form means.
export const PAST_ENGLISH: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(past).length} verbs`);
